"""PlatformIO pre-build script: writes src/git_version.h with the short commit.

The firmware shows it on the VT's main mask. A trailing "+" marks a build
with uncommitted changes. The header is only rewritten when the value
changes, so an unchanged commit doesn't trigger recompiles. It's sent at
runtime (not baked into the object pool) so a new commit doesn't change the
pool's version hash and force a VT re-upload.
"""
import pathlib
import subprocess

Import("env")  # noqa: F821 - provided by PlatformIO

project_dir = pathlib.Path(env["PROJECT_DIR"])  # noqa: F821


def git(*args):
    return subprocess.run(["git", *args], cwd=project_dir, capture_output=True,
                          text=True, check=True).stdout.strip()


try:
    commit = git("rev-parse", "--short=7", "HEAD")
    if git("status", "--porcelain", "--untracked-files=no"):
        commit += "+"
except (OSError, subprocess.CalledProcessError):
    commit = "unknown"

header = project_dir / "src" / "git_version.h"
content = ("// Generated by tools/git_version.py at build time - do not edit.\n"
           "#pragma once\n\n"
           f'#define GIT_COMMIT_SHORT "{commit}"\n')
if not header.exists() or header.read_text() != content:
    header.write_text(content)
print(f"git_version.h: {commit}")
