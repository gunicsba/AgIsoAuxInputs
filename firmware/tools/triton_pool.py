"""PlatformIO pre-build script for the joystick_seeder test env: the VT object
pool of the NeptuneGPS_Triton plough controller ("Ploegbesturing Isobus",
a separate checkout, see custom_triton_dir in platformio.ini) for a third
working set on the board (src/triton_ws.cpp).

Triton builds its pool at runtime (BuildObjectPool(), VTObjectPool.cpp), so
this compiles that code for the host with clang++ or g++ - against Triton's
own native Arduino stubs, with ISOBUS defined like its teensy41_isobus env -
runs it, and writes the pool to src/object_pool/triton_pool.h as a C array
(and as triton_plough.iop next to it). Rebuilt only when Triton's sources
are newer than the header. Also exports TRITON_CORE_DIR, so
src/CMakeLists.txt finds Triton's VTObjectPool.hpp (the object IDs).
"""
import os
import pathlib
import shutil
import subprocess
import sys
import zlib

Import("env")  # noqa: F821 - provided by PlatformIO

project_dir = pathlib.Path(env["PROJECT_DIR"])  # noqa: F821
triton_dir = (project_dir / env.GetProjectOption("custom_triton_dir")).resolve()  # noqa: F821
plough = triton_dir / "Ploegbesturing Isobus"
core = plough / "lib" / "PloegbesturingCore" / "src"
libs = triton_dir / "MeijWorks Libs"
dumper = project_dir / "tools" / "triton_pool_dump.cpp"
out_dir = project_dir / "src" / "object_pool"
header = out_dir / "triton_pool.h"

if not core.exists():
    sys.exit(f"triton_pool: {core} not found - clone NeptuneGPS_Triton there or set custom_triton_dir")
# src/CMakeLists.txt puts it on the include path (Triton's object IDs)
os.environ["TRITON_CORE_DIR"] = core.as_posix()

sources = [core / "isobus" / "VTObjectPool.cpp", core / "isobus" / "VTImages.generated.cpp",
           core / "calibration" / "PloughSettings.cpp", core / "calibration" / "CalibrationPlough.cpp",
           core / "implement" / "ImplementPlough.cpp", core / "InterfacePlough.cpp"]
inputs = [dumper, project_dir / "tools" / "triton_pool.py"] + [p for p in core.rglob("*") if p.is_file()]
if not header.exists() or header.stat().st_mtime < max(p.stat().st_mtime for p in inputs):
    compiler = shutil.which("clang++") or shutil.which("g++")
    if not compiler:
        sys.exit("triton_pool: no host C++ compiler (clang++ or g++) on PATH")
    build_dir = pathlib.Path(env.subst("$BUILD_DIR"))  # noqa: F821
    build_dir.mkdir(parents=True, exist_ok=True)
    exe = build_dir / ("triton_pool_dump" + (".exe" if os.name == "nt" else ""))
    includes = [plough / "test" / "native" / "support", core] + [
        libs / name for name in ("VehicleGuidance", "TritonIo", "EepromStore", "Interpolation",
                                 "LcdNumber", "TritonText", "ButtonPair", "EndShutoff")]
    command = [compiler, "-std=gnu++17", "-fpermissive", "-w", "-DEPOXY_DUINO=1", "-DISOBUS"]
    command += [f"-I{p}" for p in includes] + [str(dumper)] + [str(p) for p in sources] + ["-o", str(exe)]
    subprocess.run(command, check=True)
    iop = out_dir / "triton_plough.iop"
    subprocess.run([str(exe), str(iop)], check=True)
    pool = iop.read_bytes()
    # 7 chars (VT versions before 5): changes with the pool, so a VT never
    # serves a cached copy of an older one
    label = f"T{zlib.crc32(pool) & 0xFFFFFF:06X}"
    lines = [
        "// Generated by tools/triton_pool.py at build time - do not edit.",
        f"// The VT object pool of {plough} (BuildObjectPool()).",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f'#define TRITON_POOL_VERSION "{label}"',
        f"static const uint8_t TRITON_POOL[{len(pool)}] = {{",
    ]
    for row in range(0, len(pool), 24):
        lines.append("  " + ",".join(str(b) for b in pool[row:row + 24]) + ",")
    lines.append("};")
    header.write_text("\n".join(lines) + "\n")
    print(f"triton pool: {len(pool)} bytes, version {label}, from {plough}")
